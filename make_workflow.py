#!/usr/bin/env python3
"""
Generate a Windows-x64-only branded build workflow from the fork's own
.github/workflows/flutter-build.yml (so it always matches the fork's version).

    python3 make_workflow.py [path/to/flutter-build.yml] [output.yml]
"""
import sys
import yaml

src = sys.argv[1] if len(sys.argv) > 1 else ".github/workflows/flutter-build.yml"
dst = sys.argv[2] if len(sys.argv) > 2 else ".github/workflows/build-brand-windows.yml"

with open(src, encoding="utf-8") as f:
    wf = yaml.safe_load(f)

KEEP_JOBS = ["generate-bridge", "build-RustDeskTempTopMostWindow",
             "build-for-windows-flutter"]
missing = [j for j in KEEP_JOBS if j not in wf["jobs"]]
if missing:
    sys.exit(f"upstream workflow has no job(s): {missing}")

out = {
    "name": "Build branded Windows client",
    "on": {"workflow_dispatch": {"inputs": {
        "upload-artifact": {"type": "boolean", "default": True},
        "upload-tag": {"type": "string", "default": "brand"},
        "publish-update-metadata": {"type": "boolean", "default": False},
        "mode": {"type": "choice", "options": ["support", "customer"],
                 "default": "support",
                 "description": "support = full client, customer = ID/password only"},
    }}},
    "permissions": {"contents": "write"},
    # workflow_call inputs -> workflow_dispatch inputs use the same names
    "env": {k: v for k, v in wf["env"].items()},
    "jobs": {},
}
# the upstream env refers to secrets only for optional signing; keep as is.

for name in KEEP_JOBS:
    job = wf["jobs"][name]
    needs = job.get("needs")
    if needs:
        needs = [n for n in (needs if isinstance(needs, list) else [needs])
                 if n in KEEP_JOBS]
        if needs:
            job["needs"] = needs
        else:
            del job["needs"]
    out["jobs"][name] = job

# TopMostWindow helper: x64 only
tm = out["jobs"]["build-RustDeskTempTopMostWindow"]
tm["strategy"]["matrix"]["job"] = [
    j for j in tm["strategy"]["matrix"]["job"] if j.get("platform") == "x64"]
if len(tm["strategy"]["matrix"]["job"]) != 1:
    sys.exit("could not isolate the x64 TopMostWindow job")

# Windows client: x64 only, steps up to the portable exe, plus branding
bw = out["jobs"]["build-for-windows-flutter"]
bw["strategy"]["matrix"]["job"] = [
    j for j in bw["strategy"]["matrix"]["job"] if j.get("arch") == "x86_64"]
if len(bw["strategy"]["matrix"]["job"]) != 1:
    sys.exit("could not isolate the x86_64 build job")

DROP_WORDS = ("sign", "template", "msi", "verify", "publish release",
              "upload unsigned", "msbuild")
steps, branded, packed = [], False, False
for step in bw["steps"]:
    name = (step.get("name") or "").lower()
    if packed:
        break
    if any(w in name for w in DROP_WORDS):
        continue
    steps.append(step)
    if name == "checkout source code":
        steps.append({
            "name": "Apply branding",
            "shell": "bash",
            "env": {"BRAND_SERVER": "${{ secrets.RENDEZVOUS_SERVER }}",
                    "BRAND_KEY": "${{ secrets.RS_PUB_KEY }}",
                    "BRAND_MODE": "${{ inputs.mode }}"},
            "run": "python3 brand/apply_brand.py",
        })
        branded = True
    if name == "build self-extracted executable":
        steps.append({
            "name": "Rename exe",
            "shell": "bash",
            "run": 'mv ./SignOutput/rustdesk-*.exe "./SignOutput/${BRAND_APP_NAME}.exe"',
        })
        packed = True
if not branded:
    sys.exit("no 'Checkout source code' step found")
if not packed:
    sys.exit("no 'Build self-extracted executable' step found")

steps.append({
    "name": "Upload branded exe",
    "uses": "actions/upload-artifact@v4",
    "with": {"name": "branded-windows-exe-${{ inputs.mode }}",
             "path": "./SignOutput/*.exe",
             "if-no-files-found": "error"},
})
bw["steps"] = steps

with open(dst, "w", encoding="utf-8") as f:
    f.write("# Generated by make_workflow.py from flutter-build.yml\n")
    yaml.safe_dump(out, f, sort_keys=False, width=200, allow_unicode=True)
print(f"written {dst}")
